// Shifara Health - sitemap.xml and robots.txt.
//
//   node tools/sitemap.js     (tools/build.js also runs it after building the pages)
//
// The sitemap lists every page folder with an index.html, except pages marked noindex (thank-you) and the
// assets/ and tools/ folders. lastmod is the date of the last git commit that changed the page: today for
// uncommitted changes, the file's modified date when git is not available.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const SITE = (process.env.SITE_URL || 'https://shifarahealth.com').replace(/\/$/, '');
const SKIP = new Set(['assets', 'tools', 'node_modules']);
const NOINDEX = /<meta name="robots" content="[^"]*noindex/i;
const today = new Date().toISOString().slice(0, 10);

// ---------- Pages ----------
const pages = [];
(function walk(dir) {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        if (e.isFile() && e.name === 'index.html') pages.push(path.relative(ROOT, path.join(dir, e.name)).split(path.sep).join('/'));
        else if (e.isDirectory() && !e.name.startsWith('.') && !(dir === ROOT && SKIP.has(e.name))) walk(path.join(dir, e.name));
    }
})(ROOT);

// ---------- Last modified dates from git ----------
const git = args => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore'] });
const changed = new Map();
try {
    // newest commit first, so the first date seen for a file is its last change
    let date;
    for (const line of git(['log', '--format=%x00%cd', '--date=short', '--name-only', '--relative', '--', '*index.html']).split('\n')) {
        if (line.startsWith('\0')) date = line.slice(1);
        else if (line && !changed.has(line)) changed.set(line, date);
    }
    const prefix = git(['rev-parse', '--show-prefix']).trim();
    for (const line of git(['status', '--porcelain', '-uall', '--', '*index.html']).split('\n')) {
        const file = line.slice(3).split(' -> ').pop();
        if (file.startsWith(prefix)) changed.set(file.slice(prefix.length), today);
    }
} catch (e) {
    console.log('sitemap: git not available, using file modified dates');
}
const lastmod = rel => changed.get(rel) || fs.statSync(path.join(ROOT, rel)).mtime.toISOString().slice(0, 10);

// ---------- sitemap.xml ----------
const xmlEsc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const urls = pages
    .filter(rel => !NOINDEX.test(fs.readFileSync(path.join(ROOT, rel), 'utf8')))
    .map(rel => ({ loc: `${SITE}/${rel.replace(/index\.html$/, '')}`, lastmod: lastmod(rel) }))
    .sort((a, b) => (a.loc < b.loc ? -1 : a.loc > b.loc ? 1 : 0));
fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(u => `  <url>
    <loc>${xmlEsc(u.loc)}</loc>
    <lastmod>${u.lastmod}</lastmod>
  </url>`).join('\n')}
</urlset>
`);

// ---------- robots.txt ----------
// Query-string URLs (/book-consultation/?for=…, listing ?q= / ?sort= / ?path=) repeat pages that are already
// in the sitemap. noindex pages stay crawlable so search engines can read the tag.
fs.writeFileSync(path.join(ROOT, 'robots.txt'), `# Shifara Health - generated by tools/sitemap.js
User-agent: *
Allow: /assets/
Disallow: /tools/
Disallow: /*?

Sitemap: ${SITE}/sitemap.xml
`);

console.log(`sitemap.xml: ${urls.length} URLs | robots.txt written`);
